function createChecklist(role,category,entries) {
  return entries.map(([name,description,advice],index)=>({
    id:`${role.id}_${category}_${index+1}`,
    name,
    category,
    importanceLevel:category==='trait'&&index===2?'plus':'must',
    onetCode:role.code,
    description,
    advice,
  }));
}

function createOccupationRole(domain,occupation) {
  return {
    id:occupation.id,
    domainId:domain.id,
    domainName:domain.name,
    title:occupation.title,
    marketAliases:occupation.aliases,
    onetCode:occupation.code,
    onetTitle:occupation.onetTitle,
    summary:occupation.summary,
    marketDemand:occupation.marketDemand,
    taiwanIndustry:domain.industry,
    credentialNotice:occupation.credential,
    credentialSource:occupation.credentialUrl,
    typicalTasks:occupation.tasks.map((task,taskIndex)=>({
      id:`${occupation.id}_task_${taskIndex+1}`,
      title:task.title,
      category:domain.name,
      estimatedTotalMinutes:task.steps.reduce((total,step)=>total+step[5],0),
      reassuranceNote:task.reassuranceNote,
      description:task.description,
      steps:task.steps.map((step,stepIndex)=>({
        id:`${occupation.id}_task_${taskIndex+1}_step_${stepIndex+1}`,
        title:step[0],
        description:step[1],
        firstAction:step[2],
        definitionOfDone:step[3],
        tips:step[4],
        estimatedMinutes:step[5],
      })),
    })),
    checklist:[
      ...createChecklist({id:occupation.id,code:occupation.code},'skill',occupation.skills.map(name=>[
        name,
        `執行「${occupation.title}」工作時，能依現場標準完成${name}。`,
        `對照工單、檢核表或主管指示，逐項確認${name}相關要求。`,
      ])),
      ...createChecklist({id:occupation.id,code:occupation.code},'trait',occupation.traits.map(name=>[
        name,
        `工作需要展現${name}，以維持品質、合作及安全。`,
        `遇到不確定或無法完成的狀況時，依程序回報並留下紀錄。`,
      ])),
      ...createChecklist({id:occupation.id,code:occupation.code},'tool',occupation.tools.map(name=>[
        name,
        `依工作內容使用${name}，並遵守設備或系統的授權及安全規範。`,
        `使用前確認工具狀態、操作指引及適用的防護要求。`,
      ])),
      ...createChecklist({id:occupation.id,code:occupation.code},'duty',occupation.duties.map(name=>[
        name,
        `依職務分工完成${name}，並將結果交接給指定對象。`,
        `完成後依現場流程核對、登錄或通知相關人員。`,
      ])),
    ],
  };
}

